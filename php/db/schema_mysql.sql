-- Farmedia database schema for MySQL 8.0+ (InnoDB, utf8mb4).
-- Port of db/schema.sql (Supabase). Run once on an EMPTY database.
--
-- What changed compared with the Supabase version
--   * Supabase Auth (auth.users) is replaced by the `users` table. Passwords are stored only as
--     a password_hash (Argon2id, or bcrypt when Argon2 is unavailable). Nothing stores plain text.
--   * The sign-up trigger and Row Level Security are gone. The PHP code (php/src/Accounts.php)
--     writes users, profiles and consent_log in ONE transaction and enforces ownership in every query.
--   * `profiles.email` is not duplicated: the address lives only in `users.email`.
--
-- Times are stored in UTC (DATETIME). The application writes them with gmdate().

CREATE TABLE IF NOT EXISTS users (
  id                CHAR(36)     NOT NULL,            -- UUID v4, generated by the application
  email             VARCHAR(254) NOT NULL,            -- lower-cased before insert
  password_hash     VARCHAR(255) NOT NULL,
  email_verified_at DATETIME     NULL,                -- set when the confirmation link is used
  created_at        DATETIME     NOT NULL,
  updated_at        DATETIME     NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY users_email_unique (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------------
-- Legal documents: versioned Terms of Service and Privacy Policy per language.
-- Exactly one row per (doc_type, locale) may have is_current = 1. MySQL has no partial
-- indexes, so `current_key` is NULL for old versions and "doc:locale" for the current one.
-- A UNIQUE index ignores NULLs, which is what makes "one current row" enforceable.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS legal_documents (
  id           BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  doc_type     ENUM('terms', 'privacy') NOT NULL,
  locale       ENUM('tr', 'en')         NOT NULL,
  version      VARCHAR(32)     NOT NULL,
  url          VARCHAR(500)    NOT NULL,
  is_current   TINYINT(1)      NOT NULL DEFAULT 0,
  current_key  VARCHAR(16) GENERATED ALWAYS AS
               (IF(is_current = 1, CONCAT(doc_type, ':', locale), NULL)) STORED,
  published_at DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY legal_documents_version_unique (doc_type, locale, version),
  UNIQUE KEY legal_documents_one_current (current_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

