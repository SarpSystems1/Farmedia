-- ---------------------------------------------------------------------------
-- Profiles: one row per user, created in the same transaction as the account.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS profiles (
  user_id                  CHAR(36)     NOT NULL,
  first_name               VARCHAR(60)  NOT NULL DEFAULT '',
  last_name                VARCHAR(60)  NOT NULL DEFAULT '',
  role                     ENUM('hobby', 'farm') NOT NULL DEFAULT 'hobby',
  farm_size                DECIMAL(12,2) NULL,
  location                 JSON         NOT NULL,
  crops                    JSON         NOT NULL,
  preferences              JSON         NOT NULL,

  -- Region, fixed at sign-up
  country                  CHAR(2)      NOT NULL,
  jurisdiction             ENUM('kvkk', 'gdpr', 'ccpa', 'global') NOT NULL,
  locale                   ENUM('tr', 'en') NOT NULL DEFAULT 'en',

  -- Required legal acceptances, fixed at sign-up
  terms_version            VARCHAR(32)  NOT NULL,
  terms_accepted_at        DATETIME     NOT NULL,
  privacy_version          VARCHAR(32)  NOT NULL,
  privacy_accepted_at      DATETIME     NOT NULL,
  kvkk_explicit_at         DATETIME     NULL,        -- Turkey only
  kvkk_transfer_at         DATETIME     NULL,        -- Turkey only

  -- Optional, changeable consents
  alert_email_consent      TINYINT(1)   NOT NULL DEFAULT 0,
  alert_sms_consent        TINYINT(1)   NOT NULL DEFAULT 0,
  marketing_email_consent  TINYINT(1)   NOT NULL DEFAULT 0,
  alert_consent_updated_at DATETIME     NULL,

  -- CCPA: 1 = the user opted out of the sale or sharing of personal information
  do_not_sell              TINYINT(1)   NOT NULL DEFAULT 0,

  created_at               DATETIME     NOT NULL,
  updated_at               DATETIME     NOT NULL,
  PRIMARY KEY (user_id),
  CONSTRAINT profiles_user_fk FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------------
-- Sessions: one row per signed-in device. Only SHA-256 hashes of the tokens are stored.
-- Refresh rotates both tokens (the row is updated); logout sets revoked_at. Deleting a user
-- removes their sessions.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS sessions (
  id                 BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id            CHAR(36)     NOT NULL,
  access_hash        CHAR(64)     NOT NULL,
  access_expires_at  DATETIME     NOT NULL,
  refresh_hash       CHAR(64)     NOT NULL,
  refresh_expires_at DATETIME     NOT NULL,
  created_at         DATETIME     NOT NULL,
  revoked_at         DATETIME     NULL,
  PRIMARY KEY (id),
  UNIQUE KEY sessions_access_unique (access_hash),
  UNIQUE KEY sessions_refresh_unique (refresh_hash),
  KEY sessions_user_idx (user_id),
  CONSTRAINT sessions_user_fk FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------------
-- Consent log: append-only audit trail. The application never UPDATEs or DELETEs rows here,
-- except that account deletion (later step) sets user_id to NULL and fills retention_until.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS consent_log (
  id              BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id         CHAR(36)     NULL,
  consent_type    ENUM('terms', 'privacy_policy', 'kvkk_explicit', 'kvkk_transfer',
                       'alert_email', 'alert_sms', 'marketing_email', 'do_not_sell') NOT NULL,
  granted         TINYINT(1)   NOT NULL,
  version         VARCHAR(32)  NULL,
  recorded_at     DATETIME     NOT NULL,
  retention_until DATETIME     NULL,
  PRIMARY KEY (id),
  KEY consent_log_user_idx (user_id, recorded_at),
  CONSTRAINT consent_log_user_fk FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
